import { strict as assert } from "node:assert";
import { createRequire } from "node:module";
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";

import { loadIcon } from "@hugeicons/core-free-icons/loader";

import {
	HUGEICON_SHARD_COUNT,
	hugeiconShard,
} from "../src/config/library-config/icon-assets";

type IconNode = readonly [string, Readonly<Record<string, string | number>>];

const require = createRequire(import.meta.url);
const projectRoot = process.cwd();
const packageRoot = path.dirname(
	require.resolve("@hugeicons/core-free-icons/package.json"),
);
const loaderPath = path.join(packageRoot, "dist/esm/loader.web.js");
const spriteDirectory = path.join(projectRoot, "public/library-icons");
const generatedCatalogPath = path.join(
	projectRoot,
	"src/config/library-config/generated/hugeicons.ts",
);
const catalogPath = path.join(spriteDirectory, "catalog.json");

function escapeXml(value: string | number): string {
	return String(value)
		.replaceAll("&", "&amp;")
		.replaceAll('"', "&quot;")
		.replaceAll("<", "&lt;")
		.replaceAll(">", "&gt;");
}

function attributeName(name: string): string {
	return name.replace(/[A-Z]/gu, (letter) => `-${letter.toLowerCase()}`);
}

function renderNode([tag, attributes]: IconNode): string {
	const serialized = Object.entries(attributes)
		.filter(([name]) => name !== "key")
		.map(([name, value]) => `${attributeName(name)}="${escapeXml(value)}"`)
		.join(" ");
	return `<${tag}${serialized ? ` ${serialized}` : ""}/>`;
}

function renderSymbol(iconId: string, nodes: readonly IconNode[]): string {
	return `<symbol id="${iconId}" viewBox="0 0 24 24" fill="none">${nodes.map(renderNode).join("")}</symbol>`;
}

async function iconIds(): Promise<string[]> {
	const loader = await readFile(loaderPath, "utf8");
	const ids = Array.from(
		loader.matchAll(/^  ([A-Za-z0-9]+Icon): \(\) => import\(/gmu),
		(match) => match[1],
	).sort((left, right) => left.localeCompare(right));
	assert.equal(ids.length, 6_025, "Hugeicons loader must expose 6,025 icons");
	assert.equal(new Set(ids).size, ids.length, "Hugeicons icon ids must be unique");
	return ids;
}

function generatedCatalog(iconIds: readonly string[]): string {
	return [
		"// Generated by tools/generateHugeiconSprites.ts. Do not edit.",
		"export const PLATFORM_NAVBAR_ICON_IDS: readonly string[] = Object.freeze([",
		...iconIds.map((iconId) => `\t${JSON.stringify(iconId)},`),
		"]);",
		"",
		"export type PlatformNavbarIconId = string;",
		"",
	].join("\n");
}

async function expectedFiles() {
	const ids = await iconIds();
	const shards = new Map<string, string[]>();
	for (let index = 0; index < HUGEICON_SHARD_COUNT; index += 1) {
		shards.set(index.toString(16).padStart(2, "0"), []);
	}
	for (const iconId of ids) shards.get(hugeiconShard(iconId))?.push(iconId);

	const files = new Map<string, string>();
	files.set(generatedCatalogPath, generatedCatalog(ids));
	files.set(
		catalogPath,
		`${JSON.stringify(Object.fromEntries(ids.map((id) => [id, hugeiconShard(id)])))}\n`,
	);

	for (const [shard, shardIds] of shards) {
		const icons = await Promise.all(
			shardIds.map(async (iconId) => [iconId, await loadIcon(iconId)] as const),
		);
		const svg = `<svg xmlns="http://www.w3.org/2000/svg">${icons
			.map(([iconId, nodes]) => renderSymbol(iconId, nodes as readonly IconNode[]))
			.join("")}</svg>\n`;
		files.set(path.join(spriteDirectory, `${shard}.svg`), svg);
	}

	return files;
}

async function main() {
	const check = process.argv.includes("--check");
	const files = await expectedFiles();
	if (check) {
		for (const [filePath, expected] of files) {
			const actual = await readFile(filePath, "utf8").catch(() => null);
			assert.equal(
				actual,
				expected,
				`${path.relative(projectRoot, filePath)} is out of date`,
			);
		}
		return;
	}

	await mkdir(spriteDirectory, { recursive: true });
	await mkdir(path.dirname(generatedCatalogPath), { recursive: true });
	const expectedNames = new Set(
		Array.from(files.keys())
			.filter((filePath) => path.dirname(filePath) === spriteDirectory)
			.map((filePath) => path.basename(filePath)),
	);
	for (const name of await readdir(spriteDirectory)) {
		if (!expectedNames.has(name)) await rm(path.join(spriteDirectory, name));
	}
	for (const [filePath, content] of files) await writeFile(filePath, content);
	console.log(`Generated ${files.size - 1} public icon files for 6,025 Hugeicons`);
}

void main();
